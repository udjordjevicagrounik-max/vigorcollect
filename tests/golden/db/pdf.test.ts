// Golden (never delete) — task 3.3: the PDF of a demo dunning letter is generated by the real
// Chromium of the worker image, from the same HTML; the checksum is stable (same HTML → same
// bytes); it downloads only through exportService (export_log, format pdf); and the render job
// logs no personal data (no customer name, contact, invoice number).
//
// Chromium exists only in the worker image (Dockerfile, "worker" stage). On the dev host the test
// runs OUR src/server/documents/pdf.ts inside that image (docker run -i, Node strips the types,
// same cap_drop / no-new-privileges as compose). Before the image has Chromium (first build of
// 3.3) the suite is skipped with a reason — `npm run test:pdf` fails instead of skipping.

const IMAGE = process.env.PDF_TEST_IMAGE || 'collect-worker';
const SOURCE = readFileSync(join(process.cwd(), 'src/server/documents/pdf.ts'), 'utf8');

function imageHasChromium(): boolean {
  const r = spawnSync(
    'docker',
    ['run', '--rm', '--entrypoint', 'sh', IMAGE, '-c', 'test -x /usr/bin/chromium'],
    { stdio: 'ignore', timeout: 60_000 },
  );
  return r.status === 0;
}

/** renderPdf() from our source, executed by the worker image's Node + Chromium. */
function dockerRender(html: string, at: Date): Promise<PdfResult> {
  const script = `${SOURCE}
const input = ${JSON.stringify({ html, at: at.toISOString() })};
const r = await renderPdf(input.html, new Date(input.at));
process.stdout.write(JSON.stringify({ pdf: r.pdf.toString('base64'), renderer: r.renderer }));
`;
  const out = execFileSync(
    'docker',
    [
      'run',
      '--rm',
      '-i',
      '-w',
      '/app',
      '--cap-drop',
      'ALL',
      '--security-opt',
      'no-new-privileges:true',
      '--shm-size',
      '256m',
      '--entrypoint',
      'node',
      IMAGE,
      '--input-type=module-typescript',
      '-',
    ],
    {
      input: script,
      maxBuffer: 64 * 1024 * 1024,
      timeout: 120_000,
      stdio: ['pipe', 'pipe', 'ignore'],
    },
  ).toString('utf8');
  const parsed = JSON.parse(out) as { pdf: string; renderer: string };
  return Promise.resolve({ pdf: Buffer.from(parsed.pdf, 'base64'), renderer: parsed.renderer });
}

const local = chromiumPath() !== null;
const viaDocker = !local && imageHasChromium();
const render = local ? renderPdf : dockerRender;
const required = process.env.PDF_TEST_REQUIRED === '1';
if (!local && !viaDocker) {
  const why = `pdf golden: no Chromium on this host and image "${IMAGE}" has none yet (build the worker)`;
  if (required) throw new Error(why);
  process.stderr.write(`${why} — skipped\n`);
}

const keyring = parseMasterKeyring(`1:${randomBytes(32).toString('base64')}`);
process.env.DOCUMENTS_DIR = mkdtempSync(join(tmpdir(), 'golden-pdf-'));

beforeAll(async () => {
  await ensureFixtures();
  await inTenantCommit(migratePool, FX.tenantA, async (c) => {
    await c.query('SELECT provision_receivables_defaults()');
  });
});
afterAll(closePools);

function ctxFor(db: PoolClient): TenantContext {
  const requestId = randomUUID();
  return {
    db,
    tenantId: FX.tenantA,
    userId: FX.userA,
    authUserId: 'golden',
    requestId,
    requirePermission: async (key) => ({ key, scope: 'ORGANIZATION' }),
    requireAnyPermission: async (keys) => ({ key: keys[0] ?? '', scope: 'ORGANIZATION' }),
    audit: (entry) => writeAudit(db, { type: 'user', id: FX.userA }, entry, requestId),
  };
}

const NAME = 'Pdf Golden Opomena d.o.o.';
const EMAIL = 'pdf.golden@example.test';

describe.skipIf(!local && !viaDocker)(
  'golden/db: PDF of a dunning letter (worker Chromium)',
  () => {
    it('renders the demo dunning letter, stable checksum, download only via exportService, no PII in the log', async () => {
      const lines: string[] = [];
      const spy = vi
        .spyOn(process.stdout, 'write')
        .mockImplementation((chunk: string | Uint8Array) => {
          lines.push(typeof chunk === 'string' ? chunk : Buffer.from(chunk).toString('utf8'));
          return true;
        });
      const out = await inTenant(appPool, FX.tenantA, async (db) => {
        const le = await db.query<{ id: string }>(
          `SELECT find_or_create_legal_entity('RS', $1, $2, 'Europe/Belgrade', NULL) AS id`,
          [`10${randomUUID().replace(/\D/g, '').slice(0, 7)}`, NAME],
        );
        const c = await db.query<{ id: string }>(
          `INSERT INTO customers (tenant_id, legal_entity_id, display_name, owner_user_id) VALUES ($1, $2, $3, $4) RETURNING id`,
          [FX.tenantA, le.rows[0]?.id, NAME, FX.userA],
        );
        const customerId = c.rows[0]?.id ?? '';
        await createContact(db, keyring, {
          customerId,
          name: 'Pdf Kontakt',
          email: EMAIL,
          isPrimary: true,
        });
        const numbers: string[] = [];
        for (const [days, amount] of [
          [45, '120500.00'],
          [12, '9800.40'],
        ] as const) {
          const number = `PDF-${randomUUID().slice(0, 6)}`;
          numbers.push(number);
          await db.query(
            `INSERT INTO invoices (tenant_id, company_id, customer_id, source_id, external_id, number, issue_date, due_date,
                                 currency, amount_total, amount_open)
           SELECT $1, $2, $3, s.id, $4, $4, current_date - $5::int - 30, current_date - $5::int, 'EUR', $6, $6
           FROM data_sources s WHERE s.name = 'file-import'`,
            [FX.tenantA, FX.companyA, customerId, number, days, amount],
          );
        }
        const ctx = ctxFor(db);
        const { id } = await generateDocument(
          ctx,
          customerId,
          { kind: 'dunning_letter', locale: 'sr-Latn' },
          keyring,
        );
        const audit = (e: Parameters<TenantContext['audit']>[0]) =>
          writeAudit(db, { type: 'job', id: null }, e, null);
        const first = await renderDocumentPdf(db, audit, keyring, id, render);
        const second = await renderDocumentPdf(db, audit, keyring, id, render);
        const row = await db.query<{
          checksum: Buffer;
          size_bytes: number;
          renderer: string;
          created_at: Date;
        }>(
          `SELECT r.checksum, r.size_bytes, r.renderer, d.created_at FROM document_renditions r
         JOIN documents d ON d.id = r.document_id WHERE r.document_id = $1`,
          [id],
        );
        const { url } = await createDocumentLink(
          ctx,
          id,
          { purpose: 'customer_correspondence' },
          keyring,
        );
        const token = new URL(url, 'http://x').searchParams.get('token') ?? '';
        const file = await downloadDocument(ctx, id, token, keyring);
        const log = await db.query<{ format: string }>(
          `SELECT format FROM export_log WHERE filters->>'document_id' = $1`,
          [id],
        );
        return { id, first, second, row: row.rows[0], file, log: log.rows, numbers };
      });
      spy.mockRestore();
      expect(out.first).toBe('rendered');
      expect(out.second).toBe('exists');
      expect(out.row?.renderer).toMatch(/^chromium\/155\./);
      expect(out.file.format).toBe('pdf');
      expect(out.file.content.subarray(0, 5).toString('latin1')).toBe('%PDF-');
      expect(
        createHash('sha256')
          .update(out.file.content)
          .digest()
          .equals(out.row?.checksum ?? Buffer.alloc(0)),
      ).toBe(true);
      expect(out.log).toEqual([{ format: 'pdf' }]);
      const logged = lines.join('');
      expect(logged).toContain('"event":"document.render_pdf"');
      for (const secret of [NAME, EMAIL, ...out.numbers]) expect(logged).not.toContain(secret);
    }, 180_000);

    it('the same HTML and date give the same PDF bytes (stable checksum)', async () => {
      const html =
        '<!doctype html><html lang="sr-Latn"><head><meta charset="utf-8"><title>Opomena</title></head>' +
        '<body><h1>Opomena</h1><p>Dug: 120.500,00 € — čćšđž</p><table><tr><td>PDF-1</td></tr></table></body></html>';
      const at = new Date('2026-10-13T08:00:00Z');
      const a = await render(html, at);
      const b = await render(html, at);
      const sha = (x: Buffer) => createHash('sha256').update(x).digest('hex');
      expect(sha(a.pdf)).toBe(sha(b.pdf));
      expect(a.pdf.toString('latin1')).toContain("/CreationDate (D:20261013080000+00'00')");
    }, 180_000);
  },
);
